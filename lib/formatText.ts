/**
 * 基準・留意事項テキストを読みやすく整形する
 * 節・項番号の前に改行を挿入する
 */
export function formatChapterText(raw: string): string {
  return raw
    // ── PDF行折り返しの正規化（留意事項テキスト用）──────────────────
    // 「スペース + CRLF」= 段落区切り → 二重改行に変換
    .replace(/ \r\n/g, '\n\n')
    // 「CRLF」（スペースなし）= PDF折り返しによる行継続 → 結合して削除
    .replace(/\r\n/g, '')
    // ────────────────────────────────────────────────────────────────
    // 第N節・第N章 の前に二重改行（後ろにスペースが続く見出しのみ対象 — 本文中の参照は除外）
    .replace(/(?<=[^\n])(第[０-９0-9一二三四五六七八九十]+[節章])(?= )/g, '\n\n$1')
    // Ⅰ Ⅱ Ⅲ … ローマ数字見出し の前に二重改行
    .replace(/(?<=[^\n])([ⅠⅡⅢⅣⅤⅥⅦⅧⅨⅩ][　 ])/g, '\n\n$1')
    // （１）（２）… 全角数字括弧 の前に改行
    .replace(/(?<=[^\n])(（[１２３４５６７８９０]）)/g, '\n\n$1')
    // (1)(2)… 半角数字括弧 の前に改行
    .replace(/(?<=[^\n])(\([1-9]\))/g, '\n\n$1')
    // ①②③… 丸数字 の前に改行
    .replace(/(?<=[^\n])([①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮])/g, '\n$1')
    // ア イ ウ… カタカナ小見出し の前に改行（直前が改行でなく、後ろに全角スペースか半角スペース）
    .replace(/(?<=[^\n\r　 ])([ア-コ][　 ])/g, '\n$1')
    // 節・章タイトルと本文テキストの間に改行を挿入（例: 「第1節 タイトル 本文…」→「第1節 タイトル\n本文…」）
    .replace(/(第[０-９0-9一二三四五六七八九十]+[節章] \S+) /g, '$1\n')
    // Ⅰ〜Ⅹ ローマ数字タイトルと本文テキストの間に改行を挿入
    .replace(/([ⅠⅡⅢⅣⅤⅥⅦⅧⅨⅩ][　 ]\S+) /g, '$1\n')
    // 3行以上の空行を2行に圧縮
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}
